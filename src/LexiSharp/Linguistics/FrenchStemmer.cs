    /// <summary>
    /// Builds the step 1 suffix table, deduplicated and ordered longest first — the order the
    /// source's <c>[substring] among</c> gives it, and the order that makes "longest match"
    /// mean what it says. A shorter suffix listed ahead of a longer one it also matches would
    /// win, and take the wrong branch with it.
    /// </summary>
    private static KeyValuePair<string, string>[] BuildPairs(params string[] suffixes) =>
        suffixes
            .Distinct(StringComparer.Ordinal)
            .OrderByDescending(suffix => suffix.Length)
            .Select(suffix => new KeyValuePair<string, string>(suffix, suffix))
            .ToArray();
}
